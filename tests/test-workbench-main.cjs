const assert=require('node:assert/strict');
const {harness}=require('./test-behavior-platforms.cjs');
const pet=harness(.5,true);pet.settings('pet:walking',false);let seq=0;
pet.browser({id:'chrome',bounds:{x:0,y:0,width:1200,height:1000},viewports:[{x:150,y:90,width:1050,height:900}]});
const geometry={left:450,top:420,width:400,height:450,innerWidth:1050,innerHeight:900,screenX:0,screenY:0,dpr:1.25};
const send=(kind,panel=geometry)=>pet.receive({kind,panel,postId:'custom',clientId:'browser-test-client',seq:++seq,tags:[],eventId:'copy-event-'+seq});
const tick=seconds=>{for(let i=0;i<seconds/.2;i++){send('panel');pet.tick(.2);}};
send('panel');pet.tick(.1);const start=pet.state().bounds;
assert.equal(pet.state().support,null);assert.equal(start.y+start.height,1000);assert.notEqual(pet.state().action,'sit');
geometry.left+=30;geometry.top+=20;send('panel');pet.tick(.1);assert.deepEqual(pet.state().bounds,start);
pet.settings('pet:speech-settings',{workbenchSit:true});assert.equal(pet.state().workbenchSit,false,'Old setting cannot restore docking');
pet.copy();assert.equal(pet.state().audioCue.reason,'tag-copy');const copy=pet.state().audioCue.id;
send('copy');assert.equal(pet.state().audioCue.id,copy);pet.send('pet:audio-ended',copy);tick(5.2);
pet.copy();assert.equal(pet.state().audioCue.reason,'tag-copy');pet.send('pet:audio-ended',pet.state().audioCue.id);
send('leave');send('panel',null);pet.browser(null);pet.tick(1);assert.deepEqual(pet.state().bounds,start);
tick(301);assert.equal(pet.state().action,'sleep','Visible workbench no longer suppresses sleep');
assert.equal(pet.state().bounds.y+pet.state().bounds.height,1000);
const walker=harness();walker.tick(26);assert(walker.state().action.startsWith('walk-'));
console.log(JSON.stringify({noWorkbenchDock:true,oldSettingIgnored:true,taskbarWalking:true,copyLinkStillWorks:true,copyDedupe:true,sleepPreserved:true}));
